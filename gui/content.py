MATH_TEXT = """RSA MATHEMATICS (educational summary)

1. Choose two large, distinct primes p and q.
2. Compute the modulus n = p x q.   (n is public)
3. Compute Euler's totient  phi(n) = (p - 1)(q - 1).   (kept secret)
4. Choose a public exponent e with 1 < e < phi(n) and gcd(e, phi(n)) = 1.
   SecureText uses e = 65537, the common standard choice.
5. Compute the private exponent d, the modular inverse of e:
        d x e = 1 (mod phi(n))
6. Public key = (n, e).   Private key = (n, d)  (plus p and q for speed).

Textbook encryption:   c = m^e mod n
Textbook decryption:   m = c^d mod n
Textbook signature:    s = h^d mod n,  verified by  s^e mod n = h

Modular exponentiation: m^e mod n is computed with square-and-multiply, so even
2048-bit numbers take only about 2000 multiplications - never m^e followed by mod.

Why security holds: anyone can see n, but recovering p and q (factoring n) is
believed to be infeasible for 2048-bit n with known classical algorithms.

WHY TEXTBOOK RSA IS UNSAFE
- It is deterministic: the same message always gives the same ciphertext, so an
  attacker can confirm guesses.
- It is malleable: c1 x c2 mod n is a valid encryption of m1 x m2.
- Small messages with small e can be recovered by taking an ordinary e-th root.
Real systems therefore use padding: RSA-OAEP for encryption and RSA-PSS for
signatures. SecureText always uses OAEP/PSS with SHA-256.

ENCRYPTION vs HASHING vs DIGITAL SIGNATURES
- Encryption: reversible, needs a key, gives confidentiality.
- Hash (SHA-256): one-way, no key, fixed 256-bit fingerprint, gives integrity checks only.
- Digital signature: hash of the message transformed with the PRIVATE key; anyone can
  verify with the PUBLIC key. Gives authenticity, integrity and non-repudiation,
  but NOT confidentiality.

SIMPLIFIED EXAMPLE vs REAL IMPLEMENTATION
The calculator on the right uses tiny primes so you can follow every step by hand.
It is NOT secure. The real application uses 2048-bit+ keys generated by the
'cryptography' library with OAEP/PSS padding. The two must never be confused.
"""

